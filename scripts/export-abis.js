import fs from "fs";
import path from "path";

const rootDir = process.cwd();
const artifactsDir = path.join(rootDir, "artifacts", "contracts");
const targetDir = path.join(rootDir, "apps", "web", "src", "lib", "chain");

if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

// Read MockUSDC
const mockUSDCArtifact = JSON.parse(
  fs.readFileSync(path.join(artifactsDir, "MockUSDC.sol", "MockUSDC.json"), "utf8")
);

// Read PayrollStream
const payrollStreamArtifact = JSON.parse(
  fs.readFileSync(path.join(artifactsDir, "PayrollStream.sol", "PayrollStream.json"), "utf8")
);

const content = `// Auto-generated by scripts/export-abis.js
export const MOCK_USDC_ABI = ${JSON.stringify(mockUSDCArtifact.abi, null, 2)} as const;

export const PAYROLL_STREAM_ABI = ${JSON.stringify(payrollStreamArtifact.abi, null, 2)} as const;
`;

fs.writeFileSync(path.join(targetDir, "abis.ts"), content);
console.log("Exported ABIs successfully to apps/web/src/lib/chain/abis.ts");
